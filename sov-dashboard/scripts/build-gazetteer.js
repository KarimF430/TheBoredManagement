function parseCSV(csvContent) {
  const rows = []
  const lines = csvContent.trim().split('\n')

  for (let i = 1; i < lines.length; i++) {
    const line = lines[i].trim()
    if (!line) continue

    const fields = []
    let current = ''
    let inQuotes = false

    for (let j = 0; j < line.length; j++) {
      const ch = line[j]
      if (ch === '"') {
        inQuotes = !inQuotes
      } else if (ch === ',' && !inQuotes) {
        fields.push(current.trim())
        current = ''
      } else {
        current += ch
      }
    }
    fields.push(current.trim())

    if (fields.length >= 3) {
      rows.push({
        category: fields[0],
        subCategory: fields[1],
        brand: fields[2],
      })
    }
  }

  return rows
}

function extractParentBrand(brandName) {
  const parenMatch = brandName.match(/^(.+?)\s*\((.+?)\)\s*$/)
  if (parenMatch) {
    return { canonical: parenMatch[2].trim(), parent: parenMatch[1].trim() }
  }
  return { canonical: brandName }
}

function generateAliases(canonical, parent) {
  const aliases = new Set()
  const lower = canonical.toLowerCase()
  aliases.add(lower)

  if (parent) {
    aliases.add(parent.toLowerCase())
  }

  if (MANUAL_ALIASES[canonical]) {
    for (const alias of MANUAL_ALIASES[canonical]) {
      aliases.add(alias.toLowerCase())
    }
  }

  if (MANUAL_ALIASES[parent || '']) {
    for (const alias of MANUAL_ALIASES[parent || '']) {
      aliases.add(alias.toLowerCase())
    }
  }

  if (canonical.includes(' ')) {
    aliases.add(canonical.replace(/\s+/g, '').toLowerCase())
    const words = canonical.split(/\s+/)
    if (words.length === 2) {
      aliases.add(words.join(' ').toLowerCase())
    }
  }

  if (canonical.includes('/') || canonical.includes('&')) {
    const simplified = canonical.replace(/[\/&]/g, '').replace(/\s+/g, ' ').trim()
    aliases.add(simplified.toLowerCase())
  }

  if (canonical.includes("'")) {
    aliases.add(canonical.replace(/'/g, '').toLowerCase())
  }

  if (canonical.includes('.')) {
    aliases.add(canonical.replace(/\./g, '').toLowerCase())
  }

  if (canonical.includes('-')) {
    aliases.add(canonical.replace(/-/g, ' ').toLowerCase())
    aliases.add(canonical.replace(/-/g, '').toLowerCase())
  }

  if (canonical === 'boAt') {
    aliases.add('boat')
    aliases.add('bo at')
  }

  if (canonical === 'realme') {
    aliases.add('real me')
  }

  if (canonical === 'iQOO') {
    aliases.add('iqoo')
    aliases.add('i qoo')
  }

  if (canonical === 'OPPO') {
    aliases.add('oppo')
  }

  if (canonical === 'vivo') {
    aliases.add('vivo')
  }

  return Array.from(aliases)
}

const csvPath = join(__dirname, '..', '..', 'Amazon_India_Category_Brand_Master.csv')
const csvContent = readFileSync(csvPath, 'utf-8')
const rows = parseCSV(csvContent)

const brands = []
const seen = new Set()

for (const row of rows) {
  const { canonical, parent } = extractParentBrand(row.brand)
  const key = `${canonical}|${row.category}|${row.subCategory}`
  if (seen.has(key)) continue
  seen.add(key)

  brands.push({
    canonical,
    aliases: generateAliases(canonical, parent),
    category: row.category,
    subCategory: row.subCategory,
    parentBrand: parent,
  })
}

const outDir = join(__dirname, '..', 'data')
if (!existsSync(outDir)) {
  mkdirSync(outDir, { recursive: true })
}

const outPath = join(outDir, 'brand-gazetteer.json')
writeFileSync(outPath, JSON.stringify({ brands }, null, 2))

console.log(`Built gazetteer with ${brands.length} brands`)
console.log(`Output: ${outPath}`)

let totalAliases = 0
for (const brand of brands) {
  totalAliases += brand.aliases.length
}
console.log(`Total aliases: ${totalAliases}`)
